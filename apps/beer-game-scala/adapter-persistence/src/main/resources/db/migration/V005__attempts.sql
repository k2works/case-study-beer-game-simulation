-- V005: 参加・復帰の失敗の記録（接続元ごとの試行の窓。NF-S11・NF-S19）。接続元は、鍵付きの要約だけを持つ（生の IP を残さない）。
-- 失敗の回数は実 DB に持つので、複数のインスタンスで合算される。

create table attempt_failures (
    id bigint generated by default as identity,
    source_digest varchar(64) not null,
    occurred_at timestamp with time zone not null,
    constraint pk_attempt_failures primary key (id)
);

create index ix_attempt_failures_source on attempt_failures (source_digest, occurred_at);
