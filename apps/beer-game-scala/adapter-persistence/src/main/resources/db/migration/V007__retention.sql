-- V007: 保持と削除（B11。AC5.1.*）。保持の状態と、削除の受領記録。
-- 受領記録はゲームの ID を含まない（件数と時刻だけ）。削除済みのゲームは game_retention の行ごと無くなる。

create table game_retention (
    game_id uuid not null,
    retention_days int not null,
    starts_at timestamp with time zone not null,
    delete_after timestamp with time zone not null,
    status varchar(16) not null default 'SCHEDULED',
    attempt int not null default 0,
    next_attempt_at timestamp with time zone,
    last_failure_code varchar(64),
    constraint pk_game_retention primary key (game_id),
    constraint fk_game_retention_game foreign key (game_id) references game_roots (game_id),
    constraint ck_game_retention_status check (status in ('SCHEDULED', 'IN_PROGRESS', 'RETRY_PENDING', 'ABANDONED'))
);

create index ix_game_retention_due on game_retention (status, delete_after);

create table deletion_receipts (
    id bigint generated by default as identity,
    deleted_at timestamp with time zone not null,
    constraint pk_deletion_receipts primary key (id)
);
